// Run after pnpm build; uses an isolated fake solver and temporary database.
// PLAYWRIGHT_MODULE may point to an existing Playwright installation.
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { resolve } from 'node:path'
import { parameterApp, waitFor, parameters } from '../tests/fixtures/parameter-app.mjs'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright')
const extension = { id: 'surface-emissivity:Sink', adapter: 'surface-emissivity', adapterVersion: '1.0.0', adapterLabel: '表面辐射',
  label: '表面发射率', target: 'Sink', currentValue: '0.5', fingerprint: 'fixture-surface', unit: '', role: 'design',
  valueSchema: { version: 1, type: 'number', minimum: 0, maximum: 1, defaultValue: '0.9', hint: '表面发射率范围 0–1' } }
const fixture = await parameterApp({ parameters: [...parameters, extension] })
const browser = await chromium.launch({ headless: true })
const output = resolve('.thermal-agent/screenshots/parameters')
await mkdir(output, { recursive: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
try {
  await page.goto(fixture.base)
  await page.getByRole('button', { name: fixture.task.title, exact: true }).first().click()
  const workspace = page.getByRole('region', { name: '参数修改与追溯' })
  await workspace.getByLabel('选择参数').selectOption(extension.id)
  await workspace.getByRole('button', { name: '添加', exact: true }).click()
  assert.equal(await workspace.getByLabel('表面发射率 目标值').inputValue(), '0.9')
  await workspace.getByText('表面发射率范围 0–1').waitFor()
  await workspace.getByLabel('表面发射率 目标值').fill('1.2')
  await workspace.getByLabel('表面发射率 目标值').press('Tab')
  await workspace.getByText('表面发射率 超出允许范围').waitFor()
  await workspace.getByLabel('表面发射率 目标值').fill('0.9')
  await workspace.getByLabel('选择参数').selectOption('variable:FinGap')
  await workspace.getByRole('button', { name: '添加', exact: true }).click()
  await workspace.getByLabel('FinGap 目标值').fill('1.5W')
  await workspace.getByLabel('FinGap 目标值').press('Tab')
  await workspace.getByLabel('FinGap 参数用途').selectOption('design')
  await workspace.getByText(/请填写数值及单位 mm/).waitFor()
  await workspace.getByLabel('FinGap 目标值').fill('1.5mm')
  await workspace.getByLabel('FinGap 参数用途').selectOption('design')
  await workspace.getByLabel('选择参数').selectOption('material:HeatSink')
  await workspace.getByRole('button', { name: '添加', exact: true }).click()
  await workspace.getByLabel('目标值', { exact: true }).selectOption('copper')
  await workspace.getByLabel(/记录人/).fill('王工')
  await workspace.getByLabel(/修改原因/).fill('热点集中在 CPU 周围，缩小鳍片间距并将散热器替换为铜材；维持原功耗与环境温度。')
  await page.screenshot({ path: `${output}/01-editor-desktop.png`, fullPage: true })
  // Unsaved draft survives navigation away and back.
  await page.getByRole('button', { name: '返回任务列表' }).click()
  await page.getByRole('button', { name: fixture.task.title, exact: true }).first().click()
  assert.equal(await workspace.getByLabel('FinGap 目标值').inputValue(), '1.5mm')
  await workspace.getByRole('button', { name: '保存新版本并验证' }).click()
  await workspace.getByRole('button', { name: '执行 v1 候选求解' }).waitFor()
  await workspace.getByRole('button', { name: '复制为新版本' }).click()
  await workspace.getByLabel('FinGap 目标值').fill('1.2mm')
  await workspace.getByLabel(/修改原因/).fill('保留铜材，进一步缩小鳍片间距，比较两版候选。')
  await workspace.getByRole('button', { name: '保存新版本并验证' }).click()
  await workspace.getByRole('button', { name: '执行 v2 候选求解' }).waitFor()
  const plans = fixture.app.database.listParameterPlans(fixture.task.id)
  assert.deepEqual(plans.find(p => p.revision === 1).changes.find(change => change.parameter.id === extension.id).parameter.valueSchema, extension.valueSchema)
  await workspace.getByLabel('与其他版本比较').selectOption(plans.find(p => p.revision === 1).id)
  await workspace.getByRole('table', { name: '版本比较' }).waitFor()
  await workspace.scrollIntoViewIfNeeded()
  await page.screenshot({ path: `${output}/02-history-desktop.png`, fullPage: true })
  const downloadEvent = page.waitForEvent('download')
  await workspace.getByRole('button', { name: '导出追溯记录' }).click()
  const download = await downloadEvent
  assert.match(download.suggestedFilename(), /parameter-history/)
  await page.setViewportSize({ width: 375, height: 812 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.screenshot({ path: `${output}/03-history-mobile.png`, fullPage: true })
  const overflow = await workspace.evaluate(el => el.scrollWidth > el.clientWidth + 1)
  assert.equal(overflow, false, 'parameter workspace must not overflow on narrow viewport')
  await page.setViewportSize({ width: 1440, height: 1080 })
  await workspace.getByRole('button', { name: '执行 v2 候选求解' }).click()
  await waitFor(() => fixture.app.database.getTask(fixture.task.id).thermalVerdict === 'PASS')
  await workspace.getByText(/最高温度 78 °C/).waitFor({ timeout: 15000 })
  await page.screenshot({ path: `${output}/04-result-desktop.png`, fullPage: true })
  await workspace.getByLabel('选择参数').selectOption('boundary-power:CPU')
  await workspace.getByRole('button', { name: '添加', exact: true }).click()
  await workspace.getByLabel('CPU 目标值').fill('15W')
  await workspace.getByLabel(/修改原因/).fill('检查低功耗工况，单独建立新 Baseline。')
  await workspace.getByRole('button', { name: '保存新版本并验证' }).click()
  await workspace.getByRole('button', { name: '创建并求解 v3 新工况' }).waitFor()
  await workspace.getByRole('button', { name: '创建并求解 v3 新工况' }).click()
  await workspace.getByRole('button', { name: '打开工况任务' }).click()
  await page.getByRole('heading', { name: `${fixture.task.title} · 工况 v3` }).waitFor()
  await workspace.getByRole('button', { name: '查看来源任务与修改记录' }).click()
  await page.getByRole('heading', { name: fixture.task.title, exact: true }).waitFor()
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.getByRole('button', { name: '深色外观' }).click()
  await page.getByRole('button', { name: '任务', exact: true }).click()
  await page.getByRole('button', { name: fixture.task.title, exact: true }).first().click()
  await workspace.getByRole('button', { name: /v3 · 1 项修改/ }).click()
  await page.screenshot({ path: `${output}/05-history-dark.png`, fullPage: true })
  await page.setViewportSize({ width: 812, height: 375 })
  assert.equal(await workspace.evaluate(el => el.scrollWidth > el.clientWidth + 1), false)
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ success: true, screenshots: output, covered: ['edit', 'draft persistence', 'verify', 'immutable revisions', 'version comparison', 'export', '375px', 'landscape', 'inline errors', 'execute', 'result linkage', 'condition child task', 'dark mode'] }))
} catch (error) { await page.screenshot({ path: `${output}/failure.png`, fullPage: true }); console.error(await page.locator('body').innerText()); throw error } finally { await browser.close(); await fixture.close() }
