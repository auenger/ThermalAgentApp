"""Generate and re-import a public STEP thermal reference using Open CASCADE.

Run: uv run --python 3.11 --with cadquery-ocp python scripts/create-cad-reference.py
This tooling dependency is not required by the App or Icepak plugin.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from OCP.BRepAlgoAPI import BRepAlgoAPI_Fuse
from OCP.BRepGProp import BRepGProp
from OCP.BRepPrimAPI import BRepPrimAPI_MakeBox
from OCP.GProp import GProp_GProps
from OCP.gp import gp_Pnt
from OCP.IFSelect import IFSelect_RetDone
from OCP.STEPCAFControl import STEPCAFControl_Reader, STEPCAFControl_Writer
from OCP.STEPControl import STEPControl_AsIs
from OCP.TCollection import TCollection_ExtendedString
from OCP.TDataStd import TDataStd_Name
from OCP.collections import Sequence_TDF_Label
from OCP.TDocStd import TDocStd_Document
from OCP.XCAFDoc import XCAFDoc_DocumentTool


def document():
    doc = TDocStd_Document(TCollection_ExtendedString("MDTV-XCAF"))
    return doc, XCAFDoc_DocumentTool.ShapeTool_s(doc.Main())


def volume(shape):
    props = GProp_GProps()
    BRepGProp.VolumeProperties_s(shape, props)
    return props.Mass()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", default="assets/cad/reference-natural-convection.step")
    args = parser.parse_args()
    path = Path(args.output).resolve()
    path.parent.mkdir(parents=True, exist_ok=True)
    cpu = BRepPrimAPI_MakeBox(gp_Pnt(10, 10, 0), 10, 10, 2).Shape()
    sink = BRepPrimAPI_MakeBox(gp_Pnt(0, 0, 2), 30, 30, 3).Shape()
    for x in (1, 6, 11, 16, 21, 26):
        fin = BRepPrimAPI_MakeBox(gp_Pnt(x, 0, 5), 1.5, 30, 15).Shape()
        operation = BRepAlgoAPI_Fuse(sink, fin)
        if not operation.IsDone(): raise RuntimeError("fin fuse failed")
        sink = operation.Shape()
    doc, tool = document()
    for name, shape in (("CPU", cpu), ("HeatSink", sink)):
        label = tool.AddShape(shape, False)
        TDataStd_Name.Set_s(label, TCollection_ExtendedString(name))
    writer = STEPCAFControl_Writer()
    writer.SetNameMode(True)
    if not writer.Transfer(doc, STEPControl_AsIs): raise RuntimeError("STEP transfer failed")
    if writer.Write(str(path)) != IFSelect_RetDone: raise RuntimeError("STEP write failed")
    reopened, reopened_tool = document()
    reader = STEPCAFControl_Reader()
    if reader.ReadFile(str(path)) != IFSelect_RetDone or not reader.Transfer(reopened): raise RuntimeError("STEP reopen failed")
    labels = Sequence_TDF_Label()
    reopened_tool.GetFreeShapes(labels)
    volumes = sorted(volume(reopened_tool.GetShape_s(labels.Value(i))) for i in range(1, labels.Length() + 1))
    if len(volumes) != 2 or abs(volumes[0] - 200) > 1e-5 or abs(volumes[1] - 6750) > 1e-5:
        raise RuntimeError(f"Unexpected STEP volumes after reopen: {volumes}")
    metadata = {"schemaVersion": 1, "source": "Generated by repository script; no customer data", "units": "mm",
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(), "cadKernelRoundtrip": {"passed": True, "volumesMm3": volumes},
        "parts": [{"name": "CPU", "boundingBox": [10, 10, 0, 20, 20, 2], "materialSuggestion": "silicon", "powerSuggestionW": 1},
          {"name": "HeatSink", "boundingBox": [0, 0, 2, 30, 30, 20], "materialSuggestion": "aluminum", "powerSuggestionW": 0}],
        "contact": "CPU top face directly touches the heatsink base at z=2mm; no pad or contact resistance",
        "simulationAcceptance": "PENDING_WINDOWS_ICEPAK", "note": "Geometry roundtrip is not Icepak import, mesh or thermal validation. Suggested values require engineering confirmation."}
    path.with_suffix(".json").write_text(json.dumps(metadata, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({"step": str(path), "sha256": metadata["sha256"], "cadKernelRoundtrip": metadata["cadKernelRoundtrip"]}))


if __name__ == "__main__": main()
