// Real Open CASCADE WASM + real public STEP; Icepak catalog remains a labelled double.
import assert from 'node:assert/strict'
import { mkdir, readFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { modelApp } from '../tests/fixtures/model-preparation-app.mjs'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright')
const fixture = await modelApp(undefined, { realCad: true })
const browser = await chromium.launch({ headless: true, args: ['--enable-unsafe-swiftshader'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } })
page.setDefaultTimeout(20_000)
const errors = []; page.on('pageerror', e => errors.push(e.message))
const external = []; page.on('request', request => { if (!request.url().startsWith(fixture.base) && !request.url().startsWith('data:')) external.push(request.url()) })
const output = resolve('.thermal-agent/screenshots/cad-viewer'); await mkdir(output, { recursive: true })
try {
  await page.goto(fixture.base)
  await page.getByRole('button', { name: fixture.task.title, exact: true }).first().click()
  const workspace = page.locator('#cad-workspace')
  const viewer = workspace.getByRole('region', { name: 'STEP 三维预览' })
  await viewer.getByRole('button', { name: '打开 3D 预览（实验）' }).click()
  await viewer.getByText('显示网格：2 个部件 · 120 个三角形', { exact: true }).waitFor({ timeout: 60_000 })
  await viewer.screenshot({ path: `${output}/00-real-step.png` })
  assert.equal(fixture.controls.calls.length, 0, 'preview must not start Icepak')
  const canvas = viewer.locator('canvas'); await canvas.scrollIntoViewIfNeeded()
  const rect = await canvas.boundingBox()
  await canvas.click({ position: { x: rect.width / 2, y: rect.height / 2 } })
  await viewer.getByRole('heading', { name: /^显示选择：/ }).waitFor()
  await viewer.getByRole('button', { name: '显示部件 CPU', exact: true }).click()
  await viewer.getByText('尚未对应 Icepak 实体，不会修改热模型配置。', { exact: true }).waitFor()
  await workspace.getByRole('button', { name: '导入 CAD / 重新导入' }).click()
  await workspace.getByRole('button', { name: '配置此导入版本' }).click()
  await viewer.getByRole('button', { name: '显示部件 CPU', exact: true }).click()
  const context = (await fixture.request('/model-preparations')).body
  const imported = context.inspections[0]
  await viewer.getByLabel('显示部件对应实体').selectOption(imported.catalog.objects[1].key)
  assert.equal(await viewer.getByRole('button', { name: '确认显示部件对应关系' }).isEnabled(), false, 'different bounds must not bind')
  await viewer.getByLabel('显示部件对应实体').selectOption(imported.catalog.objects[0].key)
  await viewer.getByRole('button', { name: '确认显示部件对应关系' }).click()
  const panel = workspace.getByRole('complementary', { name: '选中对象上下文' })
  await panel.getByText('CPU', { exact: true }).waitFor()
  assert.equal(await workspace.getByRole('button', { name: '选择实体 CPU', exact: true }).getAttribute('aria-pressed'), 'true')
  const download = page.waitForEvent('download')
  await panel.getByRole('button', { name: '导出选中对象上下文' }).click()
  const record = JSON.parse(await readFile(await (await download).path(), 'utf8'))
  assert.equal(record.displaySelection.sourceSha256, imported.sourceSha256)
  assert.equal(record.displaySelection.catalogSha256, imported.catalogSha256)
  assert.equal(record.displaySelection.inspectionId, imported.id)
  assert.equal(record.displaySelection.confirmation, 'USER_CONFIRMED')
  assert.equal(record.evidenceKind, 'TEST_DOUBLE')
  await viewer.getByRole('button', { name: '隔离选中部件', exact: true }).click()
  await viewer.getByText('可见部件：1', { exact: true }).waitFor()
  await page.screenshot({ path: `${output}/01-mapped-cpu.png`, fullPage: true })
  await viewer.getByRole('button', { name: '显示全部部件', exact: true }).click()
  await viewer.getByText('可见部件：2', { exact: true }).waitFor()
  await viewer.getByRole('button', { name: '显示部件 HeatSink', exact: true }).click()
  assert.equal(await panel.getByRole('button', { name: '导出选中对象上下文' }).count(), 0, 'unbound mesh clears previous model selection')
  await page.setViewportSize({ width: 375, height: 812 })
  assert.equal(await workspace.evaluate(el => el.scrollWidth > el.clientWidth + 1), false)
  await viewer.scrollIntoViewIfNeeded(); await page.screenshot({ path: `${output}/02-mobile.png` })
  await page.setViewportSize({ width: 1440, height: 1080 })
  await workspace.getByRole('button', { name: '导入 CAD / 重新导入' }).click()
  await page.waitForFunction(() => [...document.querySelectorAll('#cad-workspace button')].filter(b => b.textContent === '配置此导入版本').length === 2)
  await workspace.getByRole('button', { name: '配置此导入版本' }).last().click()
  await viewer.getByRole('button', { name: '显示部件 CPU', exact: true }).click()
  await viewer.getByText('尚未对应 Icepak 实体，不会修改热模型配置。', { exact: true }).waitFor()
  await viewer.getByRole('button', { name: '关闭 3D 预览', exact: true }).click()
  assert.equal(await canvas.count(), 0)
  // Tampered downloads are rejected before the kernel parses the file.
  await page.route('**/cad-source/**', route => route.fulfill({ status: 200, body: 'tampered source' }))
  await viewer.getByRole('button', { name: '打开 3D 预览（实验）' }).click()
  await viewer.getByRole('alert').filter({ hasText: '源 CAD 身份不一致' }).waitFor()
  await viewer.getByRole('button', { name: '关闭 3D 预览' }).click()
  await page.unroute('**/cad-source/**')
  let release; const held = new Promise(done => { release = done })
  await page.route('**/cad-source/**', async route => { await held; await route.continue().catch(() => {}) })
  const pending = page.waitForRequest('**/cad-source/**')
  await viewer.getByRole('button', { name: '打开 3D 预览（实验）' }).click(); await pending
  await viewer.getByRole('button', { name: '关闭 3D 预览' }).click(); release()
  await page.unroute('**/cad-source/**', { behavior: 'wait' })
  assert.equal(await viewer.getByRole('alert').count(), 0)
  assert.deepEqual(errors, []); assert.deepEqual(external, [])
  const malformed = await modelApp()
  const badPage = await browser.newPage()
  try {
    await badPage.goto(malformed.base)
    await badPage.getByRole('button', { name: malformed.task.title, exact: true }).first().click()
    await badPage.getByRole('button', { name: '打开 3D 预览（实验）' }).click()
    await badPage.getByRole('alert').filter({ hasText: 'STEP 无法生成显示网格' }).waitFor()
    assert.equal(malformed.controls.calls.length, 0)
    assert.equal(await badPage.locator('#cad-workspace canvas').count(), 0)
  } finally { await badPage.close(); await malformed.close() }
  console.log(JSON.stringify({ passed: true, realStep: true, realWasm: true, icepakEvidence: 'TEST_DOUBLE', screenshots: output,
    covered: ['offline bundled runtime', 'preview before Icepak', 'canvas raycast', 'explicit binding', 'bounds rejection', 'object context export', 'isolation', 'unbound selection', '375px', 'new import invalidation', 'close cleanup', 'tampered source rejection', 'cancel pending download', 'malformed STEP rejection'] }))
} catch (e) {
  await page.screenshot({ path: `${output}/failure.png`, fullPage: true })
  console.error(await page.locator('#cad-workspace').innerText()); throw e
} finally { await browser.close(); await fixture.close() }
